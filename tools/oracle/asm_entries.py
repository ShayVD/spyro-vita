#!/usr/bin/env python3
"""List the entry points (glabels) of a decomp .s file with their PS1
addresses and extents, for the oracle's function traces and the host replay
test (tests/m2c_diff).
    tools/oracle/asm_entries.py FILE.s --trace     ADDR-END,... for ORACLE_TRACE
    tools/oracle/asm_entries.py FILE.s --header psx.map
        C tables for tests/m2c_diff: the entry points, and the data symbols the
        unit references (%hi/%lo) with their PS1 address and extent (up to the
        next symbol in the map), so the replay can map PS1 pointers to them."""
import re
import sys

LINE = re.compile(r"/\* [0-9A-F]+ ([0-9A-F]{8}) [0-9A-F]{8} \*/")


def entries(path):
    out, name, last = [], None, None
    for line in open(path):
        m = re.match(r"\s*glabel\s+(\w+)", line)
        if m:
            name = m.group(1)
            continue
        m = LINE.search(line)
        if m:
            a = int(m.group(1), 16)
            if name:
                out.append([name, a, None])
                name = None
            last = a
    for i, e in enumerate(out):
        e[2] = out[i + 1][1] if i + 1 < len(out) else last + 4
    return out


def map_symbols(path):
    syms = []
    for line in open(path):
        m = re.match(r"\s+0x([0-9a-f]{8})\s+(\w+)\s*$", line)
        if m:
            syms.append((int(m.group(1), 16), m.group(2)))
    syms.sort()
    out = {}
    for i, (a, n) in enumerate(syms):
        nxt = next((b for b, _ in syms[i + 1:] if b > a), a + 4)
        out.setdefault(n, (a, nxt - a))
    return out


if __name__ == "__main__":
    es = entries(sys.argv[1])
    if sys.argv[2] == "--trace":
        print(",".join(f"{a:08X}-{e:08X}" for _, a, e in es))
    else:
        print(f"/* Generated by tools/oracle/asm_entries.py from {sys.argv[1].split('/')[-1]}. */")
        for n, _, _ in es:
            print(f"extern u32 {n}__m2c(u32, u32, u32, u32);")
        print("static const struct { const char *name; u32 addr; u32 (*fn)(u32, u32, u32, u32); } k_entries[] = {")
        for n, a, _ in es:
            print(f'  {{"{n}", 0x{a:08X}u, {n}__m2c}},')
        print("};")
        refs = sorted(set(re.findall(r"%(?:hi|lo)\((\w+)", open(sys.argv[1]).read())))
        syms = map_symbols(sys.argv[3])
        for n in refs:
            print(f"extern char {n}[];")
        print("static const struct { const char *name; u32 addr, size; char *host; } k_symbols[] = {")
        for n in refs:
            a, size = syms[n]
            print(f'  {{"{n}", 0x{a:08X}u, 0x{size:X}u, {n}}},')
        print("};")
