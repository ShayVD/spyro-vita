#!/usr/bin/env python3
"""Overlay build helpers for the port (docs/porting-plan.md §4.2).

  port_overlays.py list S1_DIR
      one line per (overlay, source): `NAME|FILE|STRIP_CLASSES` for CMake.
      STRIP_CLASSES is `-` for files the Makefile doesn't strip.
  port_overlays.py preprocess --classes C --out OUT.c S1_DIR -- CPP ARGS...
      run the preprocessor, then the decomp's strip_overlay_function.py with
      the overlay's class list, the same pipeline as the decomp's Makefile.
  port_overlays.py table S1_DIR PSX_MAP OUT.c
      gen/ovl_table.c: Terminator_<ovl> pointers into the PS1 RAM arena,
      at the addresses the matching build linked them to.

The port links every overlay statically; terminator.c isn't compiled (its
function only marks the end of an overlay's code).
"""
import os
import subprocess
import sys

import yaml

STRIP = {"moby_spawn.c": "moby", "moby_update.c": "moby",
         "particle_spawn.c": "particle", "particle_update.c": "particle"}


def overlays(s1):
    with open(os.path.join(s1, "overlays/overlays.yaml")) as f:
        return [(o["name"], o["files"] or []) for o in yaml.safe_load(f)]


def classes(s1, kind, name):
    with open(os.path.join(s1, f"overlays/{kind}s.yaml")) as f:
        data = yaml.safe_load(f)
    return ",".join(str(c) for c, d in data.items()
                    if d["overlays"] is not None and (d["overlays"] == "ALL" or name in d["overlays"]))


def cmd_list(s1):
    for name, files in overlays(s1):
        for f in files:
            if f == "terminator.c":
                continue
            kind = STRIP.get(f)
            print(f"{name}|{f}|{classes(s1, kind, name) if kind else '-'}")


def cmd_preprocess(argv):
    i = argv.index("--")
    opts, cpp = argv[:i], argv[i + 1:]
    cls = opts[opts.index("--classes") + 1]
    out = opts[opts.index("--out") + 1]
    s1 = opts[-1]
    src = subprocess.run(cpp, check=True, stdout=subprocess.PIPE).stdout
    if cls != "-":
        src = subprocess.run([sys.executable, os.path.join(s1, "tools/overlays/strip_overlay_function.py"), cls],
                             input=src, check=True, stdout=subprocess.PIPE).stdout
    with open(out + ".tmp", "wb") as f:
        f.write(src)
    os.replace(out + ".tmp", out)


def cmd_table(s1, psx_map, out):
    sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
    from psxmap import load_map
    syms = load_map(psx_map)
    rows = []
    for name, _ in overlays(s1):
        s = syms.get(f"Terminator_{name}")
        if not s:
            raise SystemExit(f"Terminator_{name} not in {psx_map}")
        rows.append((name, s.addr))
    lines = ["/* Generated by tools/overlays/port_overlays.py from the matching build's",
             " * psx.map; do not edit. Overlay Terminators as PS1 RAM arena pointers. */",
             '#include "psx_arena.h"', ""]
    lines += [f"void *Terminator_{n};" for n, _ in rows]
    bss_end = None
    for line in open(psx_map):
        if "main_BSS_END = ." in line:
            bss_end = int(line.split()[0], 16)
    if bss_end is None:
        raise SystemExit(f"main_BSS_END not in {psx_map}")
    lines += ["", "extern void *g_OverlaySpacePointer;", "",
              "void psx_overlays_init(void) {",
              f"  g_OverlaySpacePointer = PSX_ARENA(0x{bss_end:08X}); /* main_BSS_END */"]
    lines += [f"  Terminator_{n} = PSX_ARENA(0x{a:08X});" for n, a in rows]
    lines += ["}", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[0] == "list":
        cmd_list(a[1])
    elif a[0] == "preprocess":
        cmd_preprocess(a[1:])
    elif a[0] == "table":
        cmd_table(*a[1:4])
