#!/usr/bin/env python3
"""A pad script for the PAL disc at its own 50 Hz from an NTSC-U one (D142).

At 50 Hz PAL's tick is still two vblanks, and its speeds are x1.2 a tick
(D135), so Spyro covers 1.2 times the US distance a vblank. The same walk
takes 5/6 of the vblanks: every state-anchored offset (`@gs=G,level=L +N`)
becomes round(N * 5/6), kept even (a tick's first vblank, as the US scripts'
are) and kept in order. Absolute lines (`V buttons`) are left alone: they
are before the game starts, at the title, and need their own times
(newgame_pal_host.txt). poke: lines keep the host's addresses; capture.lua
moves them to PAL's with ORACLE_REGION=pal.

It is a first version of a route, not a proof: check that the run reaches
the same gamestates (the anchors) as the US one.

Usage: python3 -I tools/regions/pad_pal.py IN.txt OUT.txt
"""
import re
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    out = [f"# Generated by tools/regions/pad_pal.py from {src.split('/')[-1]} (D142): its",
           "# state-anchored offsets x5/6 for the PAL disc at 50 Hz. The original's",
           "# comments follow.", ""]
    last = {}
    for line in open(src):
        m = re.match(r"^(@\S+)\s+\+(\d+)\s+(.*)$", line.rstrip("\n"))
        if not m:
            out.append(line.rstrip("\n"))
            continue
        cond, n, rest = m.group(1), int(m.group(2)), m.group(3)
        v = int(round(n * 5 / 6))
        if v % 2:
            v += 1 if n * 5 / 6 > v else -1
        pv, pn = last.get(cond, (0, 0))  # each anchor's lines stay in order,
        if n > pn and v <= pv:            # and a press doesn't merge into
            v = pv + 2                    # the line before it
        v = max(v, pv)
        last[cond] = (v, n)
        out.append(f"{cond} +{v} {rest}")
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    sys.exit(main())
