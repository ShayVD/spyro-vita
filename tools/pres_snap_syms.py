#!/usr/bin/env python3
"""The snapshot's labels (stage 7e, D125; src/game/pres/pres_snap_names.h).

Each `#define LABEL g_pres_snap_LABEL` in the names header gets its copy at
LABEL's own offset in a mirror of the game's data region (psx.map
main_DATA_START .. main_BSS_END), so the copies keep the labels' layout:
an access past one label's end reaches its neighbour's copy, as the game's
does. Writes:
  - an assembly file: the mirror (.bss) and each copy's symbol in it;
  - a C table: each copy's offset and length (to the next label), for
    pres_snap.c's copy in, and its name for the logs.

  pres_snap_syms.py --map psx.map --names pres_snap_names.h --asm OUT.S --table OUT.c
"""
import argparse
import re
import sys

DATA_LO = 0x8006BBE0
DATA_HI = 0x8007AA38


def read_map(path):
    syms = {}
    for line in open(path):
        m = re.match(r"\s+0x([0-9a-fA-F]{8,16})\s+([A-Za-z_][A-Za-z0-9_]*)\s*$", line)
        if m:
            a = int(m.group(1), 16) & 0xFFFFFFFF
            syms.setdefault(m.group(2), a)
    return syms


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--map", required=True)
    ap.add_argument("--names", required=True, action="append")
    ap.add_argument("--asm", required=True)
    ap.add_argument("--table", required=True)
    a = ap.parse_args()
    syms = read_map(a.map)
    addrs = sorted(set(v for v in syms.values() if DATA_LO <= v < DATA_HI))
    names = []
    for path in a.names:
        for n in re.findall(r"^#define\s+(\w+)\s+g_pres_snap_\1\b", open(path).read(), re.M):
            if n not in names:
                names.append(n)
    rows = []
    for n in names:
        if n not in syms:
            sys.exit("pres_snap_syms: %s isn't in %s" % (n, a.map))
        at = syms[n]
        if not DATA_LO <= at < DATA_HI:
            sys.exit("pres_snap_syms: %s (0x%08X) is outside the data region" % (n, at))
        nxt = next((x for x in addrs if x > at), DATA_HI)
        rows.append((n, at - DATA_LO, nxt - at))
    with open(a.asm, "w") as f:
        f.write("/* generated by tools/pres_snap_syms.py from %s: do not edit */\n" % ", ".join(a.names))
        f.write("  .bss\n  .balign 16\n  .globl g_pres_mirror\ng_pres_mirror:\n  .space 0x%X\n"
                % (DATA_HI - DATA_LO))
        for n, off, _ in rows:
            f.write("  .globl g_pres_snap_%s\n  .set g_pres_snap_%s, g_pres_mirror + 0x%X\n" % (n, n, off))
        f.write('  .section .note.GNU-stack,"",%progbits\n')
    with open(a.table, "w") as f:
        f.write("/* generated by tools/pres_snap_syms.py from %s: do not edit */\n" % ", ".join(a.names))
        f.write('#include "pres_snap.h"\n\n')
        # each label's own symbol, weak: a label the build keeps only at its
        # PS1 address has none (pres_snap.c checks the others are where the
        # mirror copies from, stage 7g)
        for n, _, _ in rows:
            f.write("extern char %s[] __attribute__((weak));\n" % n)
        f.write("\nconst PresSnapLabel g_pres_snap_labels[] = {\n")
        for n, off, ln in rows:
            f.write('    {"%s", 0x%X, 0x%X, %s},\n' % (n, off, ln, n))
        f.write("};\nconst int g_pres_snap_nlabels = %d;\n" % len(rows))
        f.write("const unsigned g_pres_mirror_len = 0x%X;\n" % (DATA_HI - DATA_LO))


if __name__ == "__main__":
    main()
