#!/usr/bin/env python3
"""The PS4 GLES2 renderer's pre-compiled shaders as C (decisions D199).

    tools/ps4/shaders_c.py DIR OUT.c

DIR holds the binaries a run with the player's Piglet and shader compiler
saved (config.txt shader_dump=1 -> /data/spyro/shaders/, fetched over FTP):
one file per shader, named NAME-KIND-HASH.bin, where KIND is vs or fs and
HASH is the FNV-1a of the GLSL source it was compiled from (gpu_gles.c's
src_hash). Each file is glShaderBinary's format (4 bytes, little-endian, as
glPigletGetShaderBinarySCE reported it) and then Piglet's binary. OUT.c gets
a table gpu_gles.c looks the shaders up in by name, kind and hash, so a
binary of an older source is never used. DIR missing or
empty: an empty table (the firmware's Piglet path is then off; the player's
own modules or the software renderer draw).
"""
import os
import re
import sys

NAME = re.compile(r"^([a-z0-9_]+)-(vs|fs)-([0-9a-f]{8})\.bin$")


def main():
    src_dir, out = sys.argv[1], sys.argv[2]
    entries = []
    if os.path.isdir(src_dir):
        for f in sorted(os.listdir(src_dir)):
            m = NAME.match(f)
            if not m:
                continue
            with open(os.path.join(src_dir, f), "rb") as fh:
                data = fh.read()
            if len(data) > 4:
                fmt = int.from_bytes(data[:4], "little")
                entries.append((m.group(1), m.group(2), m.group(3), fmt, data[4:]))
    lines = ["/* Generated by tools/ps4/shaders_c.py from %s: don't edit. */"
             % os.path.basename(os.path.normpath(src_dir)),
             "#include <stddef.h>",
             "#include <stdint.h>",
             "typedef struct { const char *name; int fragment; uint32_t hash; uint32_t format; "
             "const unsigned char *data; size_t size; } Ps4ShaderBlob;"]
    for i, (name, kind, h, fmt, data) in enumerate(entries):
        body = ",".join(str(b) for b in data)
        lines.append("static const unsigned char k_blob%d[%d] __attribute__((aligned(16))) = {%s};"
                     % (i, len(data), body))
    lines.append("const Ps4ShaderBlob g_ps4_shader_blobs[] = {")
    for i, (name, kind, h, fmt, data) in enumerate(entries):
        lines.append('  {"%s", %d, 0x%su, 0x%xu, k_blob%d, %d},'
                     % (name, kind == "fs", h, fmt, i, len(data)))
    lines.append("  {NULL, 0, 0, 0, NULL, 0},")
    lines.append("};")
    tmp = out + ".tmp"
    with open(tmp, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    os.replace(tmp, out)
    print("shaders_c: %d pre-compiled shaders from %s" % (len(entries), src_dir))


if __name__ == "__main__":
    main()
