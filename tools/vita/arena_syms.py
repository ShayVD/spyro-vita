#!/usr/bin/env python3
"""The game's data labels for an arena that is not at 0x80000000 (Vita,
decisions D25).

tools/data2s.py --map (D23) makes every asm/data label an absolute symbol at
its PS1 address, which only works where the arena sits at 0x80000000
(linux32). On the Vita the arena's address is known only at run time, so:

- arena_syms.h (force-included into the game's C): `#define NAME (*NAME__p)`
  for every such label. `extern T NAME;` becomes `extern T (*NAME__p);`, and
  every use of NAME reads through a pointer that start-up sets to the label's
  place in the arena.
- s1_data_vita.S: s1_data.S plus the NAME__p words, a table of
  {&NAME__p, PS1 address} (s1_vita_syms), and a table of the data words whose
  value is a label's PS1 address (s1_vita_fixups: the words' host addresses),
  which start-up moves by (arena - 0x80000000) before the image is copied.

  arena_syms.py s1_data.S out.S out.h
"""
import re
import sys

PSX_LO, PSX_HI = 0x80000000, 0x80200000
SET_RE = re.compile(r"^\.set\s+([A-Za-z_.$][\w.$]*)\s*,\s*(0x[0-9A-Fa-f]+)\s*$")
IDENT_RE = re.compile(r"[A-Za-z_.$][\w.$]*")


def split_operands(text):
    """`.long a, b - c, d` -> ['a', 'b - c', 'd'] (no parentheses in data2s output)."""
    return [p.strip() for p in text.split(",")]


def main():
    src, out_s, out_h = sys.argv[1:4]
    lines = open(src).read().split("\n")
    syms = {}
    for line in lines:
        m = SET_RE.match(line.strip())
        if m and PSX_LO <= int(m.group(2), 16) < PSX_HI:
            syms[m.group(1)] = int(m.group(2), 16)

    out = []
    fixups = 0
    for line in lines:
        s = line.strip()
        if not s.startswith(".long"):
            out.append(line)
            continue
        ops = split_operands(s[len(".long"):])
        if not any(t in syms for op in ops for t in IDENT_RE.findall(op)):
            out.append(line)
            continue
        for op in ops:
            names = [t for t in IDENT_RE.findall(op) if t in syms]
            if not names:
                out.append(f".long {op}")
                continue
            # Only `LABEL` or `LABEL +/- constant` is an address to move.
            if len(names) != 1 or not re.fullmatch(
                    rf"{re.escape(names[0])}(\s*[-+]\s*(0x[0-9A-Fa-f]+|\d+))?", op):
                raise SystemExit(f"arena_syms: cannot relocate `.long {op}`")
            out.append(f".Lvfix{fixups}: .long {op}")
            fixups += 1

    if out and out[-1].startswith(".section .note.GNU-stack"):
        tail = [out.pop()]
    else:
        tail = []
    out += ["", "/* tools/vita/arena_syms.py (decisions D25) */", ".data", ".balign 4",
            ".globl s1_vita_fixups", "s1_vita_fixups:"]
    out += [f".long .Lvfix{i}" for i in range(fixups)] + [".long 0"]
    for name in sorted(syms):
        out += [f".globl {name}__p", f"{name}__p: .long 0"]
    out += [".globl s1_vita_syms", "s1_vita_syms:"]
    out += [f".long {name}__p, 0x{addr:08X}" for name, addr in sorted(syms.items())]
    out += [".long 0, 0"] + tail
    open(out_s, "w").write("\n".join(out) + "\n")

    h = ["/* Generated by tools/vita/arena_syms.py; do not edit. The game's data",
         " * labels read through pointers into the arena (decisions D25). */",
         "#ifndef SPYRO_ARENA_SYMS_H", "#define SPYRO_ARENA_SYMS_H"]
    h += [f"#define {name} (*{name}__p)" for name in sorted(syms)]
    h += ["#endif", ""]
    open(out_h, "w").write("\n".join(h))
    print(f"arena_syms: {len(syms)} labels, {fixups} address words")


if __name__ == "__main__":
    main()
